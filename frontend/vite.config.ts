import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import path from 'node:path';

export default defineConfig({
  plugins: [react()],
  resolve: {
    alias: { '@': path.resolve(__dirname, './src') },
  },
  server: {
    port: 5173,
    // In local dev the FastAPI backend runs separately on :8000.
    // Proxying keeps the frontend calling same-origin /api paths, exactly
    // as it will on Vercel, so there is no CORS-only-in-dev surprise.
    proxy: {
      '/api': {
        target: process.env.VITE_API_PROXY || 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
    },
  },
});
